import { useState } from 'react';
import { marked } from 'marked';
import { useSEO } from '../hooks/useSEO';

export default function MarkdownPreview() {
  useSEO({
    title: 'Online Markdown Preview Tool - Live HTML Rendering',
    description: 'Free online markdown preview and converter. Write markdown and see live HTML preview instantly. Download as HTML files, copy code, and render markdown in real-time. Perfect for documentation and writing.',
    keywords: 'markdown preview, markdown to html, live preview, markdown converter, render markdown online',
  });

  const [markdown, setMarkdown] = useState('# Welcome to Markdown Preview\n\nType or paste markdown here to see the live preview on the right.\n\n## Features\n- **Live preview** updates as you type\n- **Export options**: Copy HTML, copy text, or download as HTML\n- **Support for**: headings, lists, code blocks, links, images, and more\n\n### Example Markdown\n\n```javascript\nconst greeting = "Hello, Markdown!";\nconsole.log(greeting);\n```\n\n> This is a blockquote. Great for highlighting important information.\n\n[Visit GitHub](https://github.com)');
  const [copied, setCopied] = useState('');

  const html = marked(markdown);

  const copyToClipboard = (text, type) => {
    navigator.clipboard.writeText(text);
    setCopied(type);
    setTimeout(() => setCopied(''), 2000);
  };

  const downloadAsHTML = () => {
    const fullHTML = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Markdown Preview Export</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
      line-height: 1.6;
      color: #333;
      max-width: 900px;
      margin: 0 auto;
      padding: 20px;
      background: #f5f5f5;
    }
    main {
      background: white;
      padding: 30px;
      border-radius: 8px;
      box-shadow: 0 2px 8px rgba(0,0,0,0.1);
    }
    h1, h2, h3, h4, h5, h6 {
      color: #2c3e50;
      margin-top: 24px;
      margin-bottom: 16px;
    }
    h1 { font-size: 2em; }
    h2 { font-size: 1.5em; }
    h3 { font-size: 1.25em; }
    code {
      background: #f4f4f4;
      padding: 2px 6px;
      border-radius: 3px;
      font-family: "Courier New", monospace;
      font-size: 0.9em;
    }
    pre {
      background: #2c3e50;
      color: #ecf0f1;
      padding: 15px;
      border-radius: 5px;
      overflow-x: auto;
      font-family: "Courier New", monospace;
    }
    pre code {
      background: none;
      color: inherit;
      padding: 0;
    }
    blockquote {
      border-left: 4px solid #7c3aed;
      padding-left: 15px;
      margin-left: 0;
      color: #666;
      font-style: italic;
    }
    a {
      color: #7c3aed;
      text-decoration: none;
    }
    a:hover {
      text-decoration: underline;
    }
    ul, ol {
      margin: 15px 0;
      padding-left: 30px;
    }
    li {
      margin: 8px 0;
    }
    table {
      width: 100%;
      border-collapse: collapse;
      margin: 15px 0;
    }
    th, td {
      border: 1px solid #ddd;
      padding: 12px;
      text-align: left;
    }
    th {
      background: #f4f4f4;
      font-weight: bold;
    }
    img {
      max-width: 100%;
      height: auto;
      border-radius: 5px;
    }
  </style>
</head>
<body>
  <main>
${html}
  </main>
  <footer style="text-align: center; margin-top: 40px; color: #999; font-size: 0.9em;">
    <p>Generated by CyberLock Tools Markdown Preview</p>
  </footer>
</body>
</html>`;

    const blob = new Blob([fullHTML], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `markdown-preview-${Date.now()}.html`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="tool-container">
      <h1>Online Markdown Preview Tool</h1>
      <p className="tool-intro">
        Write or paste markdown on the left to see a live HTML preview on the right. Copy the HTML output, rendered text, or download as a complete HTML file.
      </p>

      <div className="markdown-preview-container">
        {/* Input Section */}
        <div className="markdown-input-section">
          <h3>Markdown Input</h3>
          <textarea
            value={markdown}
            onChange={(e) => setMarkdown(e.target.value)}
            placeholder="Enter your markdown here..."
            className="markdown-textarea"
          />
          <div className="button-group">
            <button
              onClick={() => setMarkdown('')}
              className="btn btn-secondary"
            >
              Clear
            </button>
            <button
              onClick={() => copyToClipboard(markdown, 'markdown')}
              className="btn btn-secondary"
            >
              {copied === 'markdown' ? '✓ Copied' : 'Copy Markdown'}
            </button>
          </div>
        </div>

        {/* Preview Section */}
        <div className="markdown-preview-section">
          <h3>Live Preview</h3>
          <div
            className="markdown-preview-box"
            dangerouslySetInnerHTML={{ __html: html }}
          />
          <div className="button-group">
            <button
              onClick={() => copyToClipboard(html, 'html')}
              className="btn btn-secondary"
            >
              {copied === 'html' ? '✓ Copied HTML' : 'Copy HTML'}
            </button>
            <button
              onClick={() => copyToClipboard(markdown.replace(/#+\s+/g, '').replace(/[*_]/g, ''), 'text')}
              className="btn btn-secondary"
            >
              {copied === 'text' ? '✓ Copied Text' : 'Copy Text'}
            </button>
            <button
              onClick={downloadAsHTML}
              className="btn btn-primary"
            >
              Download HTML
            </button>
          </div>
        </div>
      </div>

      {/* Features & Info Section */}
      <div className="info-section">
        <div className="feature-item">
          <h4>📝 Supported Markdown</h4>
          <ul>
            <li><strong>Headings:</strong> # H1, ## H2, ### H3, etc.</li>
            <li><strong>Bold/Italic:</strong> **bold**, *italic*, ***both***</li>
            <li><strong>Lists:</strong> Ordered and unordered lists with nesting</li>
            <li><strong>Code:</strong> Inline `code` and code blocks with ```</li>
            <li><strong>Links:</strong> [Link text](url)</li>
            <li><strong>Images:</strong> ![Alt text](image-url)</li>
            <li><strong>Blockquotes:</strong> &gt; Start line with greater than symbol</li>
            <li><strong>Horizontal Rule:</strong> ---, ***, or ___</li>
          </ul>
        </div>

        <div className="feature-item">
          <h4>✨ Features</h4>
          <ul>
            <li>⚡ Real-time live preview as you type</li>
            <li>📋 Copy markdown source or rendered HTML</li>
            <li>💾 Download as complete HTML file with styling</li>
            <li>🎨 Professional markdown styling</li>
            <li>📱 Responsive split-pane design</li>
            <li>🔒 100% client-side - no data sent to servers</li>
          </ul>
        </div>

        <div className="feature-item">
          <h4>💡 Use Cases</h4>
          <ul>
            <li>Writing blog posts or articles in markdown</li>
            <li>Creating documentation for projects</li>
            <li>Converting README files to HTML</li>
            <li>Testing markdown syntax and formatting</li>
            <li>Learning markdown with immediate visual feedback</li>
            <li>Exporting markdown content as standalone HTML pages</li>
          </ul>
        </div>

        <div className="feature-item">
          <h4>🚀 Quick Tips</h4>
          <ul>
            <li>Start with # for headings (# H1, ## H2, etc.)</li>
            <li>Use - or * for unordered lists, numbers for ordered lists</li>
            <li>Wrap code in backticks: `code here`</li>
            <li>Use ``` for multi-line code blocks</li>
            <li>&gt; creates blockquotes for emphasis</li>
            <li>Double space at end of line creates line break</li>
          </ul>
        </div>
      </div>
    </div>
  );
}
