import { useState } from 'react';
import { marked } from 'marked';
import { useSEO } from '../hooks/useSEO';
import '../styles/pages/MarkdownPreview.css';

export default function MarkdownPreview() {
  useSEO({
    title: 'Online Markdown Preview Tool - Live HTML Rendering',
    description: 'Free online markdown preview and converter. Write markdown and see live HTML preview instantly. Download as HTML files, copy code, and render markdown in real-time. Perfect for documentation and writing.',
    keywords: 'markdown preview, markdown to html, live preview, markdown converter, render markdown online',
  });

  const [markdown, setMarkdown] = useState('# Welcome to Markdown Preview\n\nType or paste markdown here to see the live preview on the right.\n\n## Features\n- **Live preview** updates as you type\n- **Export options**: Copy HTML, copy text, or download as HTML\n- **Support for**: headings, lists, code blocks, links, images, and more\n\n### Example Markdown\n\n```javascript\nconst greeting = "Hello, Markdown!";\nconsole.log(greeting);\n```\n\n> This is a blockquote. Great for highlighting important information.\n\n[Visit GitHub](https://github.com)');
  const [copied, setCopied] = useState('');

  const html = marked(markdown);

  const copyToClipboard = (text, type) => {
    navigator.clipboard.writeText(text);
    setCopied(type);
    setTimeout(() => setCopied(''), 2000);
  };

  const downloadAsHTML = () => {
    const fullHTML = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Markdown Preview Export</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
      line-height: 1.6;
      color: #333;
      max-width: 900px;
      margin: 0 auto;
      padding: 20px;
      background: #f5f5f5;
    }
    main {
      background: white;
      padding: 30px;
      border-radius: 8px;
      box-shadow: 0 2px 8px rgba(0,0,0,0.1);
    }
    h1, h2, h3, h4, h5, h6 {
      color: #2c3e50;
      margin-top: 24px;
      margin-bottom: 16px;
    }
    h1 { font-size: 2em; }
    h2 { font-size: 1.5em; }
    h3 { font-size: 1.25em; }
    code {
      background: #f4f4f4;
      padding: 2px 6px;
      border-radius: 3px;
      font-family: "Courier New", monospace;
      font-size: 0.9em;
    }
    pre {
      background: #2c3e50;
      color: #ecf0f1;
      padding: 15px;
      border-radius: 5px;
      overflow-x: auto;
      font-family: "Courier New", monospace;
    }
    pre code {
      background: none;
      color: inherit;
      padding: 0;
    }
    blockquote {
      border-left: 4px solid #7c3aed;
      padding-left: 15px;
      margin-left: 0;
      color: #666;
      font-style: italic;
    }
    a {
      color: #7c3aed;
      text-decoration: none;
    }
    a:hover {
      text-decoration: underline;
    }
    ul, ol {
      margin: 15px 0;
      padding-left: 30px;
    }
    li {
      margin: 8px 0;
    }
    table {
      width: 100%;
      border-collapse: collapse;
      margin: 15px 0;
    }
    th, td {
      border: 1px solid #ddd;
      padding: 12px;
      text-align: left;
    }
    th {
      background: #f4f4f4;
      font-weight: bold;
    }
    img {
      max-width: 100%;
      height: auto;
      border-radius: 5px;
    }
  </style>
</head>
<body>
  <main>
${html}
  </main>
  <footer style="text-align: center; margin-top: 40px; color: #999; font-size: 0.9em;">
    <p>Generated by CyberLock Tools Markdown Preview</p>
  </footer>
</body>
</html>`;

    const blob = new Blob([fullHTML], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `markdown-preview-${Date.now()}.html`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="tool-page markdown-page">
      <div className="privacy-badge">
        All processing happens in your browser • No data is sent to server
      </div>

      <div className="tool-header">
        <span className="markdown-kicker">Live rendering</span>
        <h1>Online Markdown Preview Tool</h1>
        <p>
          Write or paste markdown on the left to see a live HTML preview on the right.
          Copy the markdown source, rendered HTML, plain text, or export a complete HTML file.
        </p>
      </div>

      <div className="tool-container">
        <section className="tool-section markdown-preview-shell">
          <div className="markdown-preview-container">
            <div className="markdown-input-section">
              <div className="markdown-section-heading">
                <span className="markdown-section-label">Editor</span>
                <h3>Markdown input</h3>
              </div>
              <textarea
                value={markdown}
                onChange={(e) => setMarkdown(e.target.value)}
                placeholder="Enter your markdown here..."
                className="markdown-textarea"
                spellCheck={false}
              />
              <div className="button-group markdown-button-group">
                <button
                  onClick={() => setMarkdown('')}
                  className="action-btn clear-btn"
                >
                  Clear
                </button>
                <button
                  onClick={() => copyToClipboard(markdown, 'markdown')}
                  className="action-btn decode-btn"
                >
                  {copied === 'markdown' ? 'Copied Markdown' : 'Copy Markdown'}
                </button>
              </div>
            </div>

            <div className="markdown-preview-section">
              <div className="markdown-section-heading">
                <span className="markdown-section-label">Preview</span>
                <h3>Live output</h3>
              </div>
              <div
                className="markdown-preview-box"
                dangerouslySetInnerHTML={{ __html: html }}
              />
              <div className="button-group markdown-button-group">
                <button
                  onClick={() => copyToClipboard(html, 'html')}
                  className="action-btn decode-btn"
                >
                  {copied === 'html' ? 'Copied HTML' : 'Copy HTML'}
                </button>
                <button
                  onClick={() => copyToClipboard(markdown.replace(/#+\s+/g, '').replace(/[*_]/g, ''), 'text')}
                  className="action-btn clear-btn"
                >
                  {copied === 'text' ? 'Copied Text' : 'Copy Text'}
                </button>
                <button
                  onClick={downloadAsHTML}
                  className="action-btn encode-btn"
                >
                  Download HTML
                </button>
              </div>
            </div>
          </div>
        </section>

        <section className="markdown-info-grid">
          <div className="info-box markdown-info-box">
            <h4>Supported Markdown</h4>
            <ul>
              <li><strong>Headings:</strong> # H1, ## H2, ### H3, and more</li>
              <li><strong>Bold and italic:</strong> **bold**, *italic*, and combined emphasis</li>
              <li><strong>Lists:</strong> Ordered, unordered, and nested lists</li>
              <li><strong>Code:</strong> Inline `code` and fenced code blocks</li>
              <li><strong>Links and images:</strong> Standard markdown link and image syntax</li>
              <li><strong>Quotes and rules:</strong> Blockquotes and horizontal dividers</li>
            </ul>
          </div>

          <div className="info-box markdown-info-box">
            <h4>Features</h4>
            <ul>
              <li>Real-time preview as you type or paste</li>
              <li>Copy markdown source, rendered HTML, or simplified plain text</li>
              <li>Download a standalone HTML export with built-in styling</li>
              <li>Split-pane layout for writing and reviewing side by side</li>
              <li>Browser-only processing for private drafts and notes</li>
            </ul>
          </div>

          <div className="info-box markdown-info-box">
            <h4>Use Cases</h4>
            <ul>
              <li>Drafting README files and project documentation</li>
              <li>Testing markdown syntax before publishing</li>
              <li>Converting markdown notes into shareable HTML</li>
              <li>Learning markdown with immediate visual feedback</li>
              <li>Reviewing how code blocks, links, and lists will render</li>
            </ul>
          </div>

          <div className="info-box markdown-info-box">
            <h4>Quick Tips</h4>
            <ul>
              <li>Use #, ##, and ### for heading hierarchy</li>
              <li>Use -, *, or numbered lines for lists</li>
              <li>Wrap inline code with backticks and blocks with triple backticks</li>
              <li>Start a line with &gt; to create a blockquote</li>
              <li>Add a blank line between sections to keep rendering predictable</li>
            </ul>
          </div>
        </section>
      </div>
    </div>
  );
}
